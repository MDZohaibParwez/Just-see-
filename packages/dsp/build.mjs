// Builds the Rust DSP to WebAssembly and embeds it in the engine as base64,
// so it loads in browsers, workers and Node without bundler setup.
// Run: node packages/dsp/build.mjs  (needs Rust + the wasm32-unknown-unknown target)
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
execSync("cargo build --release --target wasm32-unknown-unknown", { cwd: here, stdio: "inherit" });
const wasm = fs.readFileSync(path.join(here, "target/wasm32-unknown-unknown/release/just_see_dsp.wasm"));
const out = path.join(here, "../engine/src/audio/dsp-wasm.ts");
fs.writeFileSync(
  out,
  `// Generated by packages/dsp/build.mjs from the Rust sources in packages/dsp. Do not edit.\n` +
    `// ${wasm.length} bytes of WebAssembly.\n` +
    `export const DSP_WASM_BASE64 = "${wasm.toString("base64")}";\n`,
);
console.log(`wrote ${out} (${wasm.length} bytes)`);
