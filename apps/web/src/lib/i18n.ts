export const dictionaries = { en, hi } as const;
export type Locale = keyof typeof dictionaries;

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem("js.locale");
    if (saved === "en" || saved === "hi") return saved;
  } catch {
    // ignore
  }
  return navigator.language?.startsWith("hi") ? "hi" : "en";
}

export const useLocale = create<LocaleState>((set) => ({
  locale: "en",
  setLocale: (locale) => {
    try {
      localStorage.setItem("js.locale", locale);
    } catch {
      // ignore
    }
    if (typeof document !== "undefined") document.documentElement.lang = locale;
    set({ locale });
  },
}));

/** Call once on the client to pick up the saved language. */
export function hydrateLocale(): void {
  const l = initialLocale();
  useLocale.getState().setLocale(l);
}

export function translate(locale: Locale, key: MessageKey): string {
  return dictionaries[locale][key] ?? dictionaries.en[key];
}

export function useT(): (key: MessageKey) => string {
  const locale = useLocale((s) => s.locale);
  return (key) => translate(locale, key);
}
